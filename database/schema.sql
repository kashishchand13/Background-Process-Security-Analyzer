-- Background Process Security Analyzer schema for Oracle Database 21c.
-- Run while connected as the BSA schema owner, for example:
-- SQL> @database/schema.sql
-- This script creates tables and indexes only; it does not create a database or user.

CREATE TABLE systems (
    system_id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    hostname VARCHAR2(255) NOT NULL,
    os_name VARCHAR2(100) NOT NULL,
    os_version VARCHAR2(100),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    last_seen TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_systems PRIMARY KEY (system_id),
    CONSTRAINT uq_system_hostname UNIQUE (hostname)
);

CREATE TABLE scan_sessions (
    session_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    system_id NUMBER(10) NOT NULL,
    started_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    ended_at TIMESTAMP,
    session_status VARCHAR2(20) DEFAULT 'RUNNING' NOT NULL,
    processes_scanned NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_scan_sessions PRIMARY KEY (session_id),
    CONSTRAINT fk_session_system FOREIGN KEY (system_id) REFERENCES systems(system_id),
    CONSTRAINT ck_session_status CHECK (session_status IN ('RUNNING','STOPPED','ERROR')),
    CONSTRAINT ck_session_count CHECK (processes_scanned >= 0)
);

CREATE TABLE process_instances (
    process_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    system_id NUMBER(10) NOT NULL,
    pid NUMBER(10) NOT NULL,
    create_time TIMESTAMP(3) NOT NULL,
    process_name VARCHAR2(255) NOT NULL,
    executable_path VARCHAR2(1024),
    parent_pid NUMBER(10),
    parent_name VARCHAR2(255),
    username VARCHAR2(255),
    process_state VARCHAR2(40),
    priority_value NUMBER(10),
    current_cpu_percent NUMBER(9,2) DEFAULT 0 NOT NULL,
    current_memory_bytes NUMBER(19) DEFAULT 0 NOT NULL,
    current_memory_percent NUMBER(9,2) DEFAULT 0 NOT NULL,
    thread_count NUMBER(10) DEFAULT 0 NOT NULL,
    reputation_status VARCHAR2(20) DEFAULT 'UNKNOWN' NOT NULL,
    risk_score NUMBER(3) DEFAULT 0 NOT NULL,
    analysis_summary VARCHAR2(500) DEFAULT 'Not yet analyzed' NOT NULL,
    is_active CHAR(1) DEFAULT 'Y' NOT NULL,
    first_seen TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    last_seen TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_process_instances PRIMARY KEY (process_id),
    CONSTRAINT fk_process_system FOREIGN KEY (system_id) REFERENCES systems(system_id),
    CONSTRAINT uq_process_instance UNIQUE (system_id, pid, create_time),
    CONSTRAINT ck_process_active CHECK (is_active IN ('Y','N')),
    CONSTRAINT ck_process_reputation CHECK (reputation_status IN ('TRUSTED','UNKNOWN','SUSPICIOUS','BLOCKLISTED')),
    CONSTRAINT ck_process_risk CHECK (risk_score BETWEEN 0 AND 100),
    CONSTRAINT ck_process_cpu CHECK (current_cpu_percent >= 0),
    CONSTRAINT ck_process_memory CHECK (current_memory_bytes >= 0),
    CONSTRAINT ck_process_memory_pct CHECK (current_memory_percent >= 0),
    CONSTRAINT ck_process_threads CHECK (thread_count >= 0)
);

CREATE TABLE process_history (
    history_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    session_id NUMBER(19) NOT NULL,
    process_id NUMBER(19) NOT NULL,
    event_type VARCHAR2(30) NOT NULL,
    pid NUMBER(10) NOT NULL,
    process_name VARCHAR2(255) NOT NULL,
    executable_path VARCHAR2(1024),
    event_details VARCHAR2(500),
    occurred_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_process_history PRIMARY KEY (history_id),
    CONSTRAINT fk_history_session FOREIGN KEY (session_id) REFERENCES scan_sessions(session_id),
    CONSTRAINT fk_history_process FOREIGN KEY (process_id) REFERENCES process_instances(process_id),
    CONSTRAINT ck_history_event CHECK (event_type IN ('FIRST_SEEN','PROCESS_EXITED'))
);

CREATE TABLE process_metrics (
    metric_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    session_id NUMBER(19) NOT NULL,
    process_id NUMBER(19) NOT NULL,
    cpu_percent NUMBER(9,2) DEFAULT 0 NOT NULL,
    memory_bytes NUMBER(19) DEFAULT 0 NOT NULL,
    memory_percent NUMBER(9,2) DEFAULT 0 NOT NULL,
    thread_count NUMBER(10) DEFAULT 0 NOT NULL,
    io_read_bytes NUMBER(19),
    io_write_bytes NUMBER(19),
    sampled_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_process_metrics PRIMARY KEY (metric_id),
    CONSTRAINT fk_metric_session FOREIGN KEY (session_id) REFERENCES scan_sessions(session_id),
    CONSTRAINT fk_metric_process FOREIGN KEY (process_id) REFERENCES process_instances(process_id),
    CONSTRAINT ck_metric_cpu CHECK (cpu_percent >= 0),
    CONSTRAINT ck_metric_memory CHECK (memory_bytes >= 0),
    CONSTRAINT ck_metric_threads CHECK (thread_count >= 0)
);

CREATE TABLE reputation_rules (
    rule_id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    process_name VARCHAR2(255) NOT NULL,
    expected_path_prefix VARCHAR2(1024),
    sha256_hash CHAR(64),
    reputation VARCHAR2(20) NOT NULL,
    reason VARCHAR2(500) NOT NULL,
    is_enabled CHAR(1) DEFAULT 'Y' NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_reputation_rules PRIMARY KEY (rule_id),
    CONSTRAINT ck_rule_reputation CHECK (reputation IN ('TRUSTED','SUSPICIOUS','BLOCKLISTED')),
    CONSTRAINT ck_rule_enabled CHECK (is_enabled IN ('Y','N')),
    CONSTRAINT ck_rule_hash CHECK (sha256_hash IS NULL OR REGEXP_LIKE(sha256_hash, '^[0-9A-Fa-f]{64}$'))
);

CREATE TABLE detection_results (
    detection_result_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    session_id NUMBER(19) NOT NULL,
    process_id NUMBER(19) NOT NULL,
    check_type VARCHAR2(40) NOT NULL,
    verdict VARCHAR2(20) NOT NULL,
    risk_score NUMBER(3) NOT NULL,
    details CLOB NOT NULL,
    detected_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_detection_results PRIMARY KEY (detection_result_id),
    CONSTRAINT fk_detection_session FOREIGN KEY (session_id) REFERENCES scan_sessions(session_id),
    CONSTRAINT fk_detection_process FOREIGN KEY (process_id) REFERENCES process_instances(process_id),
    CONSTRAINT ck_detection_type CHECK (check_type IN ('PATH_VERIFICATION','PROCESS_HIERARCHY','RESOURCE_BEHAVIOR','REPUTATION_MATCHING','PROCESS_SPOOFING')),
    CONSTRAINT ck_detection_verdict CHECK (verdict IN ('WARNING','FAIL')),
    CONSTRAINT ck_detection_score CHECK (risk_score BETWEEN 0 AND 100),
    CONSTRAINT ck_detection_json CHECK (details IS JSON)
);

CREATE TABLE security_alerts (
    alert_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    detection_result_id NUMBER(19) NOT NULL,
    severity VARCHAR2(20) NOT NULL,
    status VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    resolved_at TIMESTAMP,
    CONSTRAINT pk_security_alerts PRIMARY KEY (alert_id),
    CONSTRAINT uq_alert_detection UNIQUE (detection_result_id),
    CONSTRAINT fk_alert_detection FOREIGN KEY (detection_result_id) REFERENCES detection_results(detection_result_id),
    CONSTRAINT ck_alert_severity CHECK (severity IN ('LOW','MEDIUM','HIGH','CRITICAL')),
    CONSTRAINT ck_alert_status CHECK (status IN ('OPEN','INVESTIGATING','RESOLVED','DISMISSED'))
);

CREATE TABLE alert_actions (
    action_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    alert_id NUMBER(19) NOT NULL,
    action_type VARCHAR2(30) NOT NULL,
    actor VARCHAR2(100) DEFAULT 'local-user' NOT NULL,
    notes CLOB,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_alert_actions PRIMARY KEY (action_id),
    CONSTRAINT fk_action_alert FOREIGN KEY (alert_id) REFERENCES security_alerts(alert_id),
    CONSTRAINT ck_action_type CHECK (action_type IN ('INVESTIGATING','NOTE_ADDED','RESOLVED','DISMISSED','REOPENED'))
);

CREATE INDEX idx_system_last_seen ON systems(last_seen);
CREATE INDEX idx_session_system_started ON scan_sessions(system_id, started_at);
CREATE INDEX idx_process_active_name ON process_instances(system_id, is_active, process_name);
CREATE INDEX idx_process_pid ON process_instances(system_id, pid);
CREATE INDEX idx_process_risk ON process_instances(risk_score, last_seen);
CREATE INDEX idx_history_occurred ON process_history(occurred_at);
CREATE INDEX idx_history_pid ON process_history(pid, occurred_at);
CREATE INDEX idx_metric_process_sampled ON process_metrics(process_id, sampled_at);
CREATE INDEX idx_metric_session_sampled ON process_metrics(session_id, sampled_at);
CREATE INDEX idx_rule_name_enabled ON reputation_rules(process_name, is_enabled);
CREATE INDEX idx_rule_hash ON reputation_rules(sha256_hash);
CREATE INDEX idx_detection_process_time ON detection_results(process_id, detected_at);
CREATE INDEX idx_detection_check_time ON detection_results(check_type, detected_at);
CREATE INDEX idx_alert_status_created ON security_alerts(status, created_at);
CREATE INDEX idx_action_alert_time ON alert_actions(alert_id, created_at);
